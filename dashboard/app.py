def kpi_card(title, value, sub=None, color="primary"):
    """Small KPI card component."""
    body = [html.H4(value, className="card-title mb-0",
                     style={"fontWeight": "700", "fontSize": "1.6rem"})]
    if sub:
        body.append(html.P(sub, className="card-text text-muted mb-0",
                           style={"fontSize": "0.75rem"}))
    return dbc.Card(
        dbc.CardBody([
            html.P(title, className="text-muted mb-1",
                   style={"fontSize": "0.75rem", "textTransform": "uppercase",
                           "letterSpacing": "1px"}),
            *body,
        ]),
        className=f"border-{color}",
        style={"borderLeft": "4px solid", "backgroundColor": "#1a1a2e"},
    )


