def pull_live_prices(tickers, end_date=None):
    """Pull adjusted close prices from yfinance since inception.

    Returns (prices, dead) where `dead` lists tickers yfinance returned nothing
    for. Yahoo silently hands back an all-NaN column for a delisted or dropped
    symbol rather than raising, so a caller that does not check ends up with a
    column of NaN masquerading as data — which is how one dead ticker used to
    wipe out the whole correlation matrix.
    """
    start = (pd.Timestamp(INCEPTION) - pd.Timedelta(days=5)).strftime("%Y-%m-%d")
    kw = dict(start=start, auto_adjust=True, progress=False)
    if end_date:
        kw["end"] = (pd.Timestamp(end_date) + pd.Timedelta(days=1)).strftime("%Y-%m-%d")
    # Download under the current live symbol, then rename back to the symbol the
    # portfolio holds, so callers never have to know a rename happened.
    fetch = [TICKER_ALIASES.get(t, t) for t in tickers]
    back = {TICKER_ALIASES.get(t, t): t for t in tickers}
    raw = yf.download(fetch, **kw)
    if isinstance(raw.columns, pd.MultiIndex):
        prices = raw["Close"].copy()
    else:
        prices = raw[["Close"]].copy()
        prices.columns = fetch
    prices = prices.rename(columns=back)
    # A symbol yfinance drops entirely is absent from the frame, not just NaN.
    prices = prices.reindex(columns=list(tickers))
    prices = prices.ffill()
    prices = prices[prices.index >= pd.Timestamp(INCEPTION)]
    dead = [t for t in prices.columns if prices[t].isna().all()]
    return prices, dead


def compute_all(end_date=None):
    """Compute every metric from live prices + snapshot CSVs."""
    snap = load_snapshot()
    eq_tickers = snap["ticker"].tolist()
    all_tickers = eq_tickers + [BENCHMARK]
    prices, dead = pull_live_prices(all_tickers, end_date=end_date)

    # A holding Yahoo no longer covers (Odontoprev/ODPV3.SA, delisted from their
    # feed) must not silently vanish: dropping it understates portfolio value and
    # every weight derived from it. Carry it at the last price the snapshot
    # recorded, and flag it so the UI can say so rather than implying it is live.
    stale = [t for t in dead if t in eq_tickers]
    if stale:
        last_known = snap.set_index("ticker")["current_px"]
        for t in stale:
            px = last_known.get(t)
            if pd.notna(px):
                prices[t] = float(px)
    # The benchmark going dark is not recoverable — every relative metric needs it.
    if BENCHMARK in dead:
        raise RuntimeError(f"benchmark {BENCHMARK} returned no price data")

    # Shares & cost from snapshot
    positions = snap.copy()

    shares = positions.set_index("ticker")["shares"]

    # Daily values — 100% equity
    eq_values = prices[eq_tickers].multiply(shares, axis=1)
    port_value = eq_values.sum(axis=1)

    port_return = port_value / port_value.iloc[0] - 1
    bench_return = prices[BENCHMARK] / prices[BENCHMARK].iloc[0] - 1

    # Daily returns
    port_daily = port_value.pct_change().dropna()
    bench_daily = prices[BENCHMARK].pct_change().dropna()
    aligned = pd.DataFrame({"port": port_daily, "bench": bench_daily}).dropna()

    # Per-stock returns
    stock_ret = prices[eq_tickers] / prices[eq_tickers].iloc[0] - 1

    # Latest P&L
    latest = prices[eq_tickers].iloc[-1]
    pos_pnl = positions.copy()
    pos_pnl["current_px"] = pos_pnl["ticker"].map(latest)
    pos_pnl["current_value"] = pos_pnl["shares"] * pos_pnl["current_px"]
    pos_pnl["pnl"] = pos_pnl["current_value"] - pos_pnl["cost_basis"]
    pos_pnl["return_pct"] = pos_pnl["pnl"] / pos_pnl["cost_basis"] * 100
    pos_pnl["weight_now"] = pos_pnl["current_value"] / port_value.iloc[-1] * 100
    pos_pnl["country_name"] = pos_pnl["country"].map(COUNTRY_NAMES)

    # Risk metrics
    ann = 252
    rf_d = (1 + RISK_FREE_ANNUAL) ** (1 / 252) - 1
    p_ann_ret = (1 + aligned["port"].mean()) ** ann - 1
    b_ann_ret = (1 + aligned["bench"].mean()) ** ann - 1
    p_ann_vol = aligned["port"].std() * np.sqrt(ann)
    b_ann_vol = aligned["bench"].std() * np.sqrt(ann)
    excess = aligned["port"] - rf_d
    active = aligned["port"] - aligned["bench"]
    sharpe = excess.mean() / aligned["port"].std() * np.sqrt(ann) if aligned["port"].std() > 0 else 0
    te = active.std() * np.sqrt(ann)
    ir = active.mean() / active.std() * np.sqrt(ann) if active.std() > 0 else 0
    cov_m = np.cov(aligned["port"], aligned["bench"])
    beta = cov_m[0, 1] / cov_m[1, 1] if cov_m[1, 1] > 0 else 0
    jensens_alpha = p_ann_ret - (RISK_FREE_ANNUAL + beta * (b_ann_ret - RISK_FREE_ANNUAL))
    treynor = (p_ann_ret - RISK_FREE_ANNUAL) / beta if beta != 0 else 0
    reg = sp_stats.linregress(aligned["bench"], aligned["port"])
    alpha_ann = reg.intercept * ann
    r2 = reg.rvalue ** 2
    dd_port = (port_value - port_value.cummax()) / port_value.cummax()
    dd_bench = (prices[BENCHMARK] - prices[BENCHMARK].cummax()) / prices[BENCHMARK].cummax()
    down = aligned["port"][aligned["port"] < 0]
    down_vol = down.std() * np.sqrt(ann) if len(down) > 0 else 0
    sortino = (p_ann_ret - RISK_FREE_ANNUAL) / down_vol if down_vol > 0 else 0
    max_dd = abs(dd_port.min())
    calmar = (p_ann_ret - RISK_FREE_ANNUAL) / max_dd if max_dd > 0 else 0
    up_d = aligned[aligned["bench"] > 0]
    dn_d = aligned[aligned["bench"] < 0]
    up_cap = up_d["port"].mean() / up_d["bench"].mean() * 100 if len(up_d) > 0 else 0
    dn_cap = dn_d["port"].mean() / dn_d["bench"].mean() * 100 if len(dn_d) > 0 else 0

    p_daily_std = aligned["port"].std()
    b_daily_std = aligned["bench"].std()

    # ── Active Share ─────────────────────────────────────────
    # AS = 0.5 * Σ|w_port_i - w_bench_i| across all securities.
    # Estimate each holding's benchmark weight via market-cap share of
    # the MSCI ACWI ex-US investable universe (~$32 T free-float mkt cap).
    ACWI_EXUS_MCAP = 32e12  # approximate total free-float market cap (USD)
    # Map currency → rough USD rate (only need order-of-magnitude accuracy)
    _CCY_TO_USD = {
        "JPY": 1/150, "GBp": 1/80, "GBP": 1.27, "ZAc": 1/1800, "ZAR": 1/18,
        "INR": 1/84, "BRL": 1/5.2, "TWD": 1/32, "IDR": 1/16000,
        "MXN": 1/17, "EUR": 1.08, "CHF": 1.10, "THB": 1/36,
        "SAR": 1/3.75, "USD": 1.0,
    }
    port_weights = pos_pnl.set_index("ticker")["weight_now"] / 100
    bench_weights = pd.Series(0.0, index=eq_tickers)
    # market_caps_live.csv is produced by scripts/fetch_market_caps.py and holds
    # mcap_usd for every holding. Reading it replaces 21 sequential
    # yf.Ticker().info round-trips (~8 s of dead time on EVERY cold load) with a
    # single file read. Market caps move far too slowly to be worth 8 s a page —
    # refresh the file by re-running that script. Any ticker missing from the
    # file still falls back to a live lookup, so nothing is lost.
    cached_mcaps = {}
    try:
        _mc = pd.read_csv(DATA / "market_caps_live.csv")
        cached_mcaps = dict(zip(_mc["ticker"], _mc["mcap_usd"]))
    except Exception:
        pass
    for tk in eq_tickers:
        mc_usd = cached_mcaps.get(tk)
        if mc_usd is None or pd.isna(mc_usd):
            try:
                info = _ticker_info(tk)
                mc = info.get("marketCap", 0) or 0
                fx = _CCY_TO_USD.get(info.get("currency", "USD"), 1.0)
                mc_usd = mc * fx
            except Exception:
                mc_usd = 0.0
        bench_weights[tk] = float(mc_usd or 0.0) / ACWI_EXUS_MCAP
    bench_weights = bench_weights.clip(upper=0.05)
    overlap = port_weights.reindex(eq_tickers).fillna(0)
    diff = (overlap - bench_weights).abs().sum()
    bench_only_weight = max(1 - bench_weights.sum(), 0)
    active_share = 0.5 * (diff + bench_only_weight)
    active_share = min(active_share, 1.0)

    # Benchmark equivalents
    b_excess = aligned["bench"] - rf_d
    b_sharpe = b_excess.mean() / aligned["bench"].std() * np.sqrt(ann) if aligned["bench"].std() > 0 else 0
    b_down = aligned["bench"][aligned["bench"] < 0]
    b_down_vol = b_down.std() * np.sqrt(ann) if len(b_down) > 0 else 0
    b_sortino = (b_ann_ret - RISK_FREE_ANNUAL) / b_down_vol if b_down_vol > 0 else 0
    b_treynor = (b_ann_ret - RISK_FREE_ANNUAL) / 1.0  # benchmark beta = 1
    b_max_dd = abs(dd_bench.min())
    b_calmar = (b_ann_ret - RISK_FREE_ANNUAL) / b_max_dd if b_max_dd > 0 else 0

    risk = {
        "Ann. Return": f"{p_ann_ret:.2%}", "Ann. Vol": f"{p_ann_vol:.2%}",
        "Daily Std Dev": f"{p_daily_std:.4%}",
        "Sharpe": f"{sharpe:.2f}", "Sortino": f"{sortino:.2f}",
        "Treynor": f"{treynor:.4f}", "Calmar": f"{calmar:.2f}",
        "Info Ratio": f"{ir:.2f}", "Tracking Error": f"{te:.2%}",
        "Beta": f"{beta:.3f}", "Alpha (ann)": f"{alpha_ann:.2%}",
        "Jensen's α": f"{jensens_alpha:.2%}",
        "R²": f"{r2:.3f}", "Max DD": f"{dd_port.min():.2%}",
        "Downside Vol": f"{down_vol:.2%}",
        "Up Capture": f"{up_cap:.1f}%", "Down Capture": f"{dn_cap:.1f}%",
        "Active Share": f"{active_share:.1%}",
    }
    bench_risk = {
        "Ann. Return": f"{b_ann_ret:.2%}", "Ann. Vol": f"{b_ann_vol:.2%}",
        "Daily Std Dev": f"{b_daily_std:.4%}",
        "Sharpe": f"{b_sharpe:.2f}", "Sortino": f"{b_sortino:.2f}",
        "Treynor": f"{b_treynor:.4f}", "Calmar": f"{b_calmar:.2f}",
        "Info Ratio": "—", "Tracking Error": "—",
        "Beta": "1.000", "Alpha (ann)": "0.00%",
        "Jensen's α": "0.00%",
        "R²": "1.000", "Max DD": f"{dd_bench.min():.2%}",
        "Downside Vol": f"{b_down_vol:.2%}",
        "Up Capture": "100.0%", "Down Capture": "100.0%",
        "Active Share": "0.0%",
    }
    risk_df = pd.DataFrame({
        "Metric": list(risk.keys()),
        "Portfolio": list(risk.values()),
        "Benchmark": list(bench_risk.values()),
    })

    # ── Correlation ──────────────────────────────────────────
    # `.dropna()` defaults to how="any", so a single all-NaN column (one dead
    # ticker) deleted EVERY row and left an empty frame — corr() then returned
    # all-NaN and the heatmap rendered blank. Three changes:
    #   · drop dead/stale tickers by column, not by row
    #   · drop rows only when the whole row is empty (a holiday in one market
    #     should not discard that day for the other twenty names)
    #   · correlate pairwise with a min_periods floor, so a partial gap costs
    #     one cell instead of the matrix
    corr_tickers = [t for t in eq_tickers if t not in stale]
    eq_dr = prices[corr_tickers].pct_change()
    eq_dr = eq_dr.dropna(axis=1, how="all").dropna(how="all")
    name_map = positions.set_index("ticker")["name"]
    eq_dr.columns = [name_map.get(t, t) for t in eq_dr.columns]
    corr = eq_dr.corr(min_periods=20)

    # ── FX attribution ───────────────────────────────────────
    # Map each country code → yfinance FX ticker (CCY→USD rate)
    _FX_MAP = {
        "GB": "GBPUSD=X", "JP": "JPYUSD=X", "ZA": "ZARUSD=X",
        "IN": "INRUSD=X", "BR": "BRLUSD=X", "TW": "TWDUSD=X",
        "ID": "IDRUSD=X", "MX": "MXNUSD=X", "IT": "EURUSD=X",
        "FR": "EURUSD=X", "DE": "EURUSD=X", "CH": "CHFUSD=X",
        "TH": "THBUSD=X", "SA": "SARUSD=X",
    }
    fx_tickers = list(set(_FX_MAP.values()))
    try:
        fx_prices = yf.download(
            fx_tickers,
            start=(pd.Timestamp(prices.index[0]) - pd.Timedelta(days=5)).strftime("%Y-%m-%d"),
            end=(pd.Timestamp(prices.index[-1]) + pd.Timedelta(days=1)).strftime("%Y-%m-%d"),
            auto_adjust=True, progress=False,
        )
        if isinstance(fx_prices.columns, pd.MultiIndex):
            fx_prices = fx_prices["Close"]
        fx_prices = fx_prices.ffill().reindex(prices.index, method="ffill")
    except Exception:
        fx_prices = pd.DataFrame(index=prices.index)

    fx_attr = []
    for _, row in positions.iterrows():
        tk = row["ticker"]
        ctry = row["country"]
        fx_tk = _FX_MAP.get(ctry)
        local_ret = (prices[tk].iloc[-1] / prices[tk].iloc[0] - 1) * 100
        if fx_tk and fx_tk in fx_prices.columns:
            fx_start = fx_prices[fx_tk].iloc[0]
            fx_end = fx_prices[fx_tk].iloc[-1]
            if pd.notna(fx_start) and pd.notna(fx_end) and fx_start > 0:
                fx_ret = (fx_end / fx_start - 1) * 100
                usd_ret = ((1 + local_ret / 100) * (1 + fx_ret / 100) - 1) * 100
            else:
                fx_ret = 0.0
                usd_ret = local_ret
        else:
            fx_ret = 0.0
            usd_ret = local_ret
        fx_attr.append({
            "name": row["name"], "ticker": tk, "country": ctry,
            "local_ret": round(local_ret, 2),
            "fx_ret": round(fx_ret, 2),
            "usd_ret": round(usd_ret, 2),
        })
    fx_df = pd.DataFrame(fx_attr)

    # ── Fama-French 5-factor decomposition ─────────────────────
    # ETF-proxy factors (Kenneth French data lags; ETFs are real-time)
    _FF_TICKERS = ["ACWX", "SCZ", "EFA", "EFV", "EFG", "IQLT", "EFAV"]
    try:
        ff_raw = yf.download(
            _FF_TICKERS,
            start=(pd.Timestamp(prices.index[0]) - pd.Timedelta(days=5)).strftime("%Y-%m-%d"),
            end=(pd.Timestamp(prices.index[-1]) + pd.Timedelta(days=1)).strftime("%Y-%m-%d"),
            auto_adjust=True, progress=False,
        )
        if isinstance(ff_raw.columns, pd.MultiIndex):
            ff_px = ff_raw["Close"]
        else:
            ff_px = ff_raw
        ff_px = ff_px.ffill().reindex(prices.index, method="ffill")
        ff_ret = ff_px.pct_change().dropna()

        rf_daily = (1 + RISK_FREE_ANNUAL) ** (1 / 252) - 1
        ff_factors = pd.DataFrame({
            "MKT-RF": ff_ret["ACWX"] - rf_daily,
            "SMB":    ff_ret["SCZ"] - ff_ret["EFA"],
            "HML":    ff_ret["EFV"] - ff_ret["EFG"],
            "RMW":    ff_ret["IQLT"] - ff_ret["ACWX"],
            "CMA":    ff_ret["EFAV"] - ff_ret["ACWX"],
        })
        # Align with portfolio excess returns
        y = (port_daily - rf_daily).reindex(ff_factors.index).dropna()
        X = ff_factors.reindex(y.index).dropna()
        y = y.reindex(X.index)
        X_const = sm.add_constant(X)
        ff5_model = sm.OLS(y, X_const).fit()
        ff5_result = {
            "params": ff5_model.params,
            "tvalues": ff5_model.tvalues,
            "pvalues": ff5_model.pvalues,
            "rsquared": ff5_model.rsquared,
            "rsquared_adj": ff5_model.rsquared_adj,
            "alpha_ann": ff5_model.params.get("const", 0) * 252,
            "nobs": int(ff5_model.nobs),
            "factor_sum": X.sum().to_dict(),   # cumulative factor returns over period
            "port_excess_cum": float(y.sum()),  # cumulative portfolio excess return
        }
    except Exception:
        ff5_result = {"error": traceback.format_exc()}

    result = {
        "prices": prices,
        "port_return": port_return,
        "bench_return": bench_return,
        "port_value": port_value,
        "pos_pnl": pos_pnl,
        "stock_ret": stock_ret,
        "dd_port": dd_port,
        "dd_bench": dd_bench,
        "risk_df": risk_df,
        "corr": corr,
        "aligned": aligned,
        "reg": reg,
        "beta": beta,
        "alpha_ann": alpha_ann,
        "r2": r2,
        "sharpe": sharpe,
        "p_ann_ret": p_ann_ret,
        "p_ann_vol": p_ann_vol,
        "max_dd_val": dd_port.min(),
        "ir": ir,
        "name_map": name_map,
        "fx_df": fx_df,
        "ff5": ff5_result,
        "stale_tickers": stale,
    }
    return result
