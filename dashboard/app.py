    port_bb_yield = (div_df["Buyback Yield %"].fillna(0) * div_df["_wt"]).sum()
    port_total_sh_yield = port_avg_yield + port_bb_yield
    div_df.drop(columns=["_wt"], inplace=True)

    price_only_ret = total_ret
