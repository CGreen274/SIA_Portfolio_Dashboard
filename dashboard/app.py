        # Pull market cap & daily volume from yfinance (convert to USD)
        # Fetch FX rates once for all needed currencies
        fx_cache = {}
        # yfinance reports currency as minor unit (ZAc, GBp) for some exchanges
        # but marketCap is already in the major unit (ZAR, GBP). Map to major.
        _MINOR_TO_MAJOR = {"ZAC": "ZAR", "GBP": "GBP"}  # GBp→GBP, ZAc→ZAR
        def _to_usd(value, ccy):
            if value is None or ccy is None:
                return None
            ccy = ccy.upper()
            if ccy == "USD":
                return value
            # Map minor-unit label to major currency (no division —
            # marketCap is already in the major unit)
            ccy = _MINOR_TO_MAJOR.get(ccy, ccy)
            if ccy not in fx_cache:
                pair = f"{ccy}USD=X"
                try:
                    rate_data = yf.Ticker(pair).history(period="1d")
                    fx_cache[ccy] = rate_data["Close"].iloc[-1] if len(rate_data) else None
                except Exception:
                    fx_cache[ccy] = None
            rate = fx_cache.get(ccy)
            return value * rate if rate else None

