        """Return (trailing, forward) yields as decimals (0.02 = 2%)."""
        raw_fwd = info.get("dividendYield")
        fwd = raw_fwd / 100 if raw_fwd is not None else None
        raw_trail = info.get("trailingAnnualDividendYield")
